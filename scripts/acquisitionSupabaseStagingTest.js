'use strict';
// Real hosted Supabase validation. Never accepts ROOK production or calls other providers.
const fs=require('node:fs');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const {createClient}=require('@supabase/supabase-js');
const {SupabaseAcquisitionStore}=require('../backend/organicAcquisition/store');
async function run(){
 if(!process.argv.includes('--confirm-isolated-staging'))throw Error('Isolated staging confirmation required');
 const file=process.env.ACQ_STAGING_CREDENTIAL_FILE;
 if(!file)throw Error('Secure staging credential file required');
 if(fs.statSync(file).mode&0o077)throw Error('Staging credential file must be private');
 const credential=JSON.parse(fs.readFileSync(file,'utf8'));
 const url=new URL(credential.url),expected=process.env.ACQ_STAGING_PROJECT_REF;
 if(!expected||expected==='nazycunakcwfmusmiybd'||url.origin!=='https://'+expected+'.supabase.co'||url.pathname!=='/')throw Error('Explicit isolated staging project required; production refused');
 const options={auth:{persistSession:false,autoRefreshToken:false,detectSessionInUrl:false}};
 const client=createClient(url.origin,credential.secret,options),store=new SupabaseAcquisitionStore(client);
 const publicClient=createClient(url.origin,credential.publicKey,options),checks=[];
 const marker=await store.call('get',{kind:'config',id:'provider-persistence-probe'});
 assert.equal(marker?.synthetic,true);assert.equal(marker.probe,'ROOK-STAGING-20261021');
 checks.push('Existing server adapter reaches the explicitly marked isolated Supabase branch');
 const id='staging-'+crypto.randomUUID(),stamp=Date.now(),iso=t=>new Date(t).toISOString();
 await store.call('put',{kind:'config',id,body:{synthetic:true,id}});
 const fresh=new SupabaseAcquisitionStore(createClient(url.origin,credential.secret,options));
 assert.equal((await fresh.call('get',{kind:'config',id})).id,id);
 checks.push('Write persists across separate SDK clients and REST requests');
 const anonRpc=await publicClient.rpc('rook_acq_command',{op:'get',a:{kind:'config',id}});
 assert.equal(anonRpc.error?.code,'42501');
 const anonLedger=await publicClient.from('rook_acq_commissions').select('customer_id').limit(1);
 assert.equal(anonLedger.error?.code,'42501');
 checks.push('Public API key cannot execute sidecar RPC or read the commission ledger');
 await store.call('enqueue',{id,lane:id,channel:'nonpublic-staging-only',payload:{synthetic:true},dueAt:iso(stamp-1000)});
 const claims=await Promise.all(['worker-a','worker-b'].map(token=>store.call('claim',{lane:id,token,now:iso(stamp)})));
 assert.equal(claims.filter(Boolean).length,1);
 const claimed=claims.find(Boolean);
 await store.call('outcome',{id,token:claimed.lease_token,status:'published',receipt:{synthetic:true,id:'not-a-provider-receipt'},dueAt:iso(stamp)});
 checks.push('Concurrent hosted workers acquire exactly one lease; receipt survives REST persistence');
 const identity='synthetic-identity-'+id,partnerIdentity='synthetic-partner-'+id;
 await store.call('put',{kind:'config',id:'launch',body:{baselineComplete:true,goLiveAt:iso(stamp-86400000),synthetic:true}});
 await store.call('enroll',{id,userId:'partner-'+id,identityHash:partnerIdentity,status:'active',synthetic:true});
 assert.equal((await store.call('bind',{userId:id,partnerId:id,identityHash:identity,boundAt:iso(stamp-3600000),expiresAt:iso(stamp+86400000)})).bound,true);
 const payment={eventId:id,eligible:true,userId:id,customerId:id,identityHash:identity,fingerprintHash:'synthetic-card-'+id,invoiceId:id,subscriptionId:id,invoiceCreatedAt:iso(stamp-60000),paidAt:iso(stamp),amountCents:1999,channel:'synthetic_referral'};
 assert.equal((await store.call('paid',payment)).credited,true);
 await store.call('paid',payment);await store.call('paid',{...payment,eventId:id+'-duplicate'});
 const ledger=await store.call('commissions',{partnerId:id});
 assert.equal(ledger.length,1);assert.equal(ledger[0].amount_cents,500);
 assert.equal(ledger[0].status,'held');
 checks.push('Synthetic referral ledger creates one $5 held commission despite duplicate invoice/event attempts');
 await store.call('reverse',{invoiceId:id,reason:'synthetic_refund_test'});
 assert.equal((await store.call('commissions',{partnerId:id}))[0].status,'reversed');
 checks.push('Synthetic refund reversal persists; no Stripe transaction or payment is represented as real');
 await store.call('put',{kind:'baseline',id:id+'-existing',body:{identityHash:id+'-existing'}});
 assert.equal((await store.call('bind',{userId:id+'-existing',identityHash:id+'-existing',partnerId:id})).reason,'existing_customer');
 checks.push('Existing-customer exclusion remains enforced by the hosted database');
 const report={environment:'real isolated Supabase preview branch',realSupabase:true,completedAt:new Date().toISOString(),checks,realStripeTestMode:false,realSocialDelivery:false,realEmailDelivery:false,productionTouched:false,secretsRecorded:false,syntheticFinancialRecords:true};
 fs.writeFileSync('docs/organic-growth/SUPABASE_STAGING_RESULT.json',JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report,null,2));
}
run().catch(()=>{console.error('Supabase staging validation failed. Secret values and provider response bodies suppressed.');process.exitCode=1;});
